package com.kuronami.isekaiapi.gametest.wood;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.kuronami.isekaiapi.IsekaiApi;
import com.kuronami.isekaiapi.api.wood.WoodSet;
import com.kuronami.isekaiapi.examples.wood.ExampleWoodMod;
import com.kuronami.isekaiapi.impl.wood.validation.PackProbe;
import com.kuronami.isekaiapi.impl.wood.validation.WoodSetAudit;
import com.kuronami.isekaiapi.impl.wood.validation.WoodSetProbe;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.tags.BlockTags;
import net.minecraft.tags.ItemTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.neoforged.neoforge.gametest.GameTestHolder;
import net.neoforged.neoforge.gametest.PrefixGameTestTemplate;

/**
 * Acceptance for {@code /isekai validate}: a complete species reports nothing, and a species with
 * one hole per kind reports exactly those holes and nothing else.
 *
 * <p>The example species is the complete case because it is a real one — blocks registered through
 * the public builder, data generated by the bundled generators, loaded from a data pack. The broken
 * case is the same species behind a probe that hides one artefact of each kind, which is how a
 * consumer's forgotten file looks from the inside.
 */
@GameTestHolder(IsekaiApi.MODID)
public final class WoodSetValidationGameTests {

    /** Every kind an audit can report, so "one of each" can be asserted as a set. */
    private static final Set<WoodSetAudit.Kind> ALL_KINDS = EnumSet.allOf(WoodSetAudit.Kind.class);

    private WoodSetValidationGameTests() {}

    private static WoodSet example() {
        WoodSet set = ExampleWoodMod.example;
        if (set == null) {
            throw new IllegalStateException(
                    "the example species was not registered — this must run on a GameTest server");
        }
        return set;
    }

    private static ResourceManager resources(GameTestHelper helper) {
        return helper.getLevel().getServer().getResourceManager();
    }

    /**
     * The example species is complete: its loot tables, tags, recipes, blockstates, models,
     * textures and names are all found through the packs the server has selected.
     */
    @PrefixGameTestTemplate(false)
    @GameTest(template = "empty3x3x3")
    public static void completeSpeciesReportsNothing(GameTestHelper helper) {
        WoodSetAudit.Report report = WoodSetAudit.audit(ExampleWoodMod.MOD_ID, resources(helper));
        if (report.sets() != 1) {
            helper.fail("expected the example species, found " + report.sets() + " set(s) in "
                    + ExampleWoodMod.MOD_ID);
            return;
        }
        if (!report.isOk()) {
            helper.fail("a complete species reported " + report.findings().size()
                    + " gap(s): " + report.messages());
            return;
        }
        if (report.checks() < 100) {
            helper.fail("only " + report.checks() + " checks ran; the audit is not looking at much");
            return;
        }
        if (report.skipped() != 0) {
            helper.fail("skipped " + report.skipped()
                    + " check(s) even though both layers are visible");
            return;
        }
        helper.succeed();
    }

    /**
     * One hole in each of the eight kinds is reported as eight findings, one per kind — no kind is
     * silent, and nothing is reported twice or invented.
     */
    @PrefixGameTestTemplate(false)
    @GameTest(template = "empty3x3x3")
    public static void oneHolePerKindIsReportedOnceByKind(GameTestHelper helper) {
        WoodSetProbe broken = new HoledProbe(new PackProbe(resources(helper)), example());
        WoodSetAudit.Report report = WoodSetAudit.run(ExampleWoodMod.MOD_ID, broken);

        List<WoodSetAudit.Kind> kinds = new ArrayList<>();
        for (WoodSetAudit.Finding finding : report.findings()) {
            kinds.add(finding.kind());
        }
        if (report.findings().size() != ALL_KINDS.size()) {
            helper.fail("expected " + ALL_KINDS.size() + " findings, got "
                    + report.findings().size() + ": " + report.messages());
            return;
        }
        if (!EnumSet.copyOf(kinds).equals(ALL_KINDS)) {
            helper.fail("findings did not cover every kind once: " + kinds);
            return;
        }
        helper.succeed();
    }

    /**
     * A layer this side cannot see is counted as skipped, never as missing: a dedicated server that
     * did not load a consumer's resource pack must not be told its models are gone.
     */
    @PrefixGameTestTemplate(false)
    @GameTest(template = "empty3x3x3")
    public static void invisibleLayerIsSkippedNotReported(GameTestHelper helper) {
        for (WoodSetAudit.Layer hidden : WoodSetAudit.Layer.values()) {
            WoodSetAudit.Report report = WoodSetAudit.run(ExampleWoodMod.MOD_ID,
                    new LayerBlindProbe(new PackProbe(resources(helper)), hidden));
            if (!report.isOk()) {
                helper.fail("hiding " + hidden + " reported " + report.findings().size()
                        + " gap(s) that cannot be seen from there: " + report.messages());
                return;
            }
            if (report.skipped() == 0) {
                helper.fail("hiding " + hidden + " reported no skips, so an invisible layer and a "
                        + "complete one would look the same");
                return;
            }
        }
        helper.succeed();
    }

    /** A namespace that declares no wood set produces no output at all. */
    @PrefixGameTestTemplate(false)
    @GameTest(template = "empty3x3x3")
    public static void namespaceWithoutSpeciesIsQuiet(GameTestHelper helper) {
        WoodSetAudit.Report report = WoodSetAudit.audit(IsekaiApi.MODID, resources(helper));
        if (report.sets() != 0 || !report.isOk() || report.checks() != 0) {
            helper.fail("a namespace with no species reported sets=" + report.sets()
                    + ", checks=" + report.checks() + ", findings=" + report.messages());
            return;
        }
        helper.succeed();
    }

    /**
     * The complete species minus one artefact of each kind.
     *
     * <p>Only one of each is hidden so the finding count is a fixed number: hiding a blockstate also
     * stops the models it points at from being walked, and two holes of the same kind collapse into
     * one finding because findings are keyed by kind and subject.
     */
    private static final class HoledProbe implements WoodSetProbe {

        private final WoodSetProbe delegate;

        private final ResourceLocation lootTable;
        private final ResourceLocation blockstate;
        private final ResourceLocation model;
        private final ResourceLocation texture;
        private final ResourceLocation language;
        private final String hiddenLanguageKey;
        private final String hiddenRecipeMarker;

        private final Block unburnableLog;
        private final Item untaggedPlanks;

        private HoledProbe(WoodSetProbe delegate, WoodSet set) {
            this.delegate = delegate;
            String namespace = set.id().getNamespace();
            Block door = set.door().orElseThrow().get();
            this.lootTable = file(namespace, "loot_table/"
                    + set.fence().orElseThrow().get().getLootTable().location().getPath() + ".json");
            this.blockstate = file(namespace, "blockstates/" + blockPath(door) + ".json");
            this.model = file(namespace,
                    "models/item/" + itemPath(set.slab().orElseThrow().get().asItem()) + ".json");
            this.texture = file(namespace,
                    "textures/block/" + blockPath(set.sapling().orElseThrow().get()) + ".png");
            this.language = file(namespace, "lang/en_us.json");
            this.hiddenLanguageKey = door.getDescriptionId();
            this.hiddenRecipeMarker =
                    BuiltInRegistries.ITEM.getKey(set.stairs().orElseThrow().get().asItem()).toString();
            this.unburnableLog = set.log().orElseThrow().get();
            this.untaggedPlanks = set.planks().orElseThrow().get().asItem();
        }

        private static ResourceLocation file(String namespace, String path) {
            return ResourceLocation.fromNamespaceAndPath(namespace, path);
        }

        private static String blockPath(Block block) {
            return BuiltInRegistries.BLOCK.getKey(block).getPath();
        }

        private static String itemPath(Item item) {
            return BuiltInRegistries.ITEM.getKey(item).getPath();
        }

        @Override
        public boolean seesData(String namespace) {
            return delegate.seesData(namespace);
        }

        @Override
        public boolean seesAssets(String namespace) {
            return delegate.seesAssets(namespace);
        }

        @Override
        public Optional<String> readData(ResourceLocation id) {
            if (id.equals(lootTable)) {
                return Optional.empty();
            }
            return delegate.readData(id);
        }

        @Override
        public Optional<String> readAsset(ResourceLocation id) {
            if (id.equals(blockstate) || id.equals(model) || id.equals(texture)) {
                return Optional.empty();
            }
            if (id.equals(language)) {
                return delegate.readAsset(id).map(this::withoutHiddenKey);
            }
            return delegate.readAsset(id);
        }

        private String withoutHiddenKey(String text) {
            JsonObject json = JsonParser.parseString(text).getAsJsonObject();
            json.remove(hiddenLanguageKey);
            return json.toString();
        }

        @Override
        public Map<ResourceLocation, String> listData(String namespace, String directory) {
            Map<ResourceLocation, String> files = delegate.listData(namespace, directory);
            if (!"recipe".equals(directory)) {
                return files;
            }
            Map<ResourceLocation, String> kept = new LinkedHashMap<>(files);
            kept.entrySet().stream()
                    .filter(entry -> entry.getValue().contains(hiddenRecipeMarker))
                    .findFirst()
                    .ifPresent(entry -> kept.remove(entry.getKey()));
            return kept;
        }

        @Override
        public boolean inBlockTag(Block block, TagKey<Block> tag) {
            if (block == unburnableLog && tag.equals(BlockTags.LOGS_THAT_BURN)) {
                return false;
            }
            return delegate.inBlockTag(block, tag);
        }

        @Override
        public boolean inItemTag(Item item, TagKey<Item> tag) {
            if (item == untaggedPlanks && tag.equals(ItemTags.PLANKS)) {
                return false;
            }
            return delegate.inItemTag(item, tag);
        }
    }

    /** A probe that reports one layer as not visible, as a server without that layer would. */
    private static final class LayerBlindProbe implements WoodSetProbe {

        private final WoodSetProbe delegate;
        private final WoodSetAudit.Layer hidden;

        private LayerBlindProbe(WoodSetProbe delegate, WoodSetAudit.Layer hidden) {
            this.delegate = delegate;
            this.hidden = hidden;
        }

        @Override
        public boolean seesData(String namespace) {
            return hidden != WoodSetAudit.Layer.DATA && delegate.seesData(namespace);
        }

        @Override
        public boolean seesAssets(String namespace) {
            return hidden != WoodSetAudit.Layer.ASSETS && delegate.seesAssets(namespace);
        }

        @Override
        public Optional<String> readData(ResourceLocation id) {
            return delegate.readData(id);
        }

        @Override
        public Optional<String> readAsset(ResourceLocation id) {
            return delegate.readAsset(id);
        }

        @Override
        public Map<ResourceLocation, String> listData(String namespace, String directory) {
            return delegate.listData(namespace, directory);
        }

        @Override
        public boolean inBlockTag(Block block, TagKey<Block> tag) {
            return delegate.inBlockTag(block, tag);
        }

        @Override
        public boolean inItemTag(Item item, TagKey<Item> tag) {
            return delegate.inItemTag(item, tag);
        }
    }
}
